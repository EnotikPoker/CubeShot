#!/usr/bin/env python3
"""Offline asset authoring only. Normal builds consume the checked-in PNG/header."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
letters=list(dict.fromkeys([chr(n) for n in range(32,127)]+[chr(n) for n in range(0x410,0x450)]+list('Ёё←→↑↓—–…°×«»✓✕')))
columns=16;cell_w=44;cell_h=48
rows=(len(letters)+columns-1)//columns
atlas=Image.new('RGBA',(columns*cell_w,rows*cell_h*2))
draw=ImageDraw.Draw(atlas)
metrics=[]
for weight_index,weight in enumerate((450,650)):
 font=ImageFont.truetype(str(ROOT/'assets/fonts/Rubik.ttf'),32)
 font.set_variation_by_axes([weight])
 ascent,descent=font.getmetrics()
 for index,letter in enumerate(letters):
  left,top,right,bottom=font.getbbox(letter,anchor='ls')
  x=(index%columns)*cell_w+2;y=(index//columns+weight_index*rows)*cell_h+2
  draw.text((x-left,y-top),letter,font=font,fill=(255,255,255,255),anchor='ls')
  metrics.append(f'{{{ord(letter)}u,{weight_index},{x},{y},{right-left},{bottom-top},{left},{ascent+top},{font.getlength(letter):.5f}f}}')
atlas.save(ROOT/'assets/font.png')
header='''// Generated by tools/bake_visual_font.py from Rubik (OFL).\n#pragma once\n#include <array>\nnamespace cubeshot::client {\nstruct FontGlyph { unsigned code,weight; int x,y,width,height,left,top; float advance; };\ninline constexpr std::array<FontGlyph,'''+str(len(metrics))+'> fontGlyphs{{\n'+',\n'.join(metrics)+'\n}};\n}\n'
(ROOT/'src/client/FontAtlas.h').write_text(header)
print('Baked',len(metrics),'glyphs',atlas.size)
